"""Build results/BENCHMARK.md (+ plots) from the benchmark CSVs and apply the selection
rule programmatically so the recommendation is reproducible.

python -m bench.report
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

import numpy as np

R = Path("results")


def read(path):
    p = R / path
    if not p.exists():
        return []
    with open(p) as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        for k, v in r.items():
            try:
                r[k] = float(v)
            except (TypeError, ValueError):
                pass
    return rows


def fmt(v, nd=3):
    if isinstance(v, float):
        if np.isnan(v):
            return "–"
        return f"{v:.{nd}f}"
    return str(v)


def table(rows, cols, headers=None, nd=3):
    headers = headers or cols
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join(fmt(r.get(c, ""), nd) for c in cols) + " |")
    return "\n".join(out)


def model_size_mb(tag: str) -> float:
    for part in tag.split("|"):
        if part.startswith("model="):
            p = Path("models") / part.split("=", 1)[1]
            if p.exists():
                return p.stat().st_size / 1e6
    if tag.startswith("mediapipe"):
        return (Path("models/pretrained/iris_landmark.tflite").stat().st_size / 1e6
                if Path("models/pretrained/iris_landmark.tflite").exists() else 2.6)
    return 0.0


def select(rows, dice_tol=0.01, fail_tol=0.02, ms_budget=1000.0):
    """Cheapest config within `dice_tol` of the best mean iris Dice, failure rate within
    `fail_tol` of the best, and p95 latency under budget. Cost = (p95 ms, model MB)."""
    if not rows:
        return None, None
    best_d = max(r["dice_iris_mean"] for r in rows)
    best_f = min(r["fail_rate_dice<0.8"] for r in rows)
    ok = [r for r in rows if r["dice_iris_mean"] >= best_d - dice_tol
          and r["fail_rate_dice<0.8"] <= best_f + fail_tol and r["ms_p95"] <= ms_budget]
    ok.sort(key=lambda r: (r["ms_p95"] + 20 * r["size_mb"]))
    top = max(rows, key=lambda r: r["dice_iris_mean"])
    return (ok[0] if ok else top), top


def pareto(rows):
    pts = sorted(rows, key=lambda r: r["ms_p50"])
    front, best = [], -1
    for r in pts:
        if r["dice_iris_mean"] > best:
            front.append(r)
            best = r["dice_iris_mean"]
    return front


def plot(rows, front, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fam = lambda t: t.split("|")[0]  # noqa: E731
    colors = {"daugman": "#4C78A8", "hough": "#F58518", "raycast": "#54A24B", "mediapipe": "#B279A2",
              "onnx": "#E45756", "hybrid": "#72B7B2"}
    fig, ax = plt.subplots(figsize=(7.5, 4.6), dpi=150)
    for f in sorted({fam(r["tag"]) for r in rows}):
        rs = [r for r in rows if fam(r["tag"]) == f]
        ax.scatter([r["ms_p50"] for r in rs], [r["dice_iris_mean"] for r in rs], s=22, label=f,
                   color=colors.get(f, "gray"), alpha=0.85, edgecolor="none")
    ax.plot([r["ms_p50"] for r in front], [r["dice_iris_mean"] for r in front], "k--", lw=0.8, label="Pareto front")
    ax.set_xscale("log")
    ax.set_xlabel("median latency per image, 1 CPU thread (ms, log)")
    ax.set_ylabel("mean visible-iris Dice (UBIRIS.v2 test)")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8, frameon=False, loc="lower right")
    ax.set_title("Iris segmentation: accuracy vs cost", fontsize=10)
    fig.tight_layout()
    fig.savefig(path)


def main():
    md = ["# A-EYE iris pipeline – benchmark results", "",
          "_Generated by `python -m bench.report` from the CSVs in `results/`. All numbers measured in this "
          "repository's container (4 vCPU, no GPU). Data: see `data/DATASETS.md` (research-only licences)._", ""]
    seg = [r for r in read("seg/summary.csv") if r.get("dataset") == "ubiris_v2"]
    seg_x = [r for r in read("seg/summary.csv") if r.get("dataset") != "ubiris_v2"]
    for r in seg:
        r["size_mb"] = model_size_mb(r["tag"])
    choice, top = select(seg)
    md += ["## 1. Recommendation", ""]
    if choice:
        md += [f"* **Default segmenter (balanced):** `{choice['tag']}` – iris Dice {fmt(choice['dice_iris_mean'])}, "
               f"failure rate {fmt(choice['fail_rate_dice<0.8'])}, p95 {fmt(choice['ms_p95'], 0)} ms/image, "
               f"model {fmt(choice['size_mb'], 1)} MB.",
               f"* **Max accuracy:** `{top['tag']}` – iris Dice {fmt(top['dice_iris_mean'])}, p95 {fmt(top['ms_p95'], 0)} ms.",
               "* Selection rule: cheapest config (p95 latency + 20 ms per MB of model) whose mean iris Dice is within "
               "0.01 of the best and whose failure rate (Dice < 0.8) is within 2 points of the best.", ""]
    extra = R / "notes.md"
    if extra.exists():
        md += [extra.read_text(), ""]
    if seg:
        front = pareto(seg)
        plot(seg, front, R / "seg_pareto.png")
        md += ["## 2. Segmentation (UBIRIS.v2 held-out subjects)", "", "![pareto](seg_pareto.png)", "",
               "Pareto front (no config is both faster and more accurate):", "",
               table(front, ["tag", "dice_iris_mean", "fail_rate_dice<0.8", "e1_mean", "dice_pupil_mean", "ms_p50", "ms_p95", "size_mb"],
                     ["config", "iris Dice", "fail rate", "E1", "pupil Dice", "ms p50", "ms p95", "MB"]), "",
               "<details><summary>All segmentation configs</summary>", "",
               table(sorted(seg, key=lambda r: -r["dice_iris_mean"]),
                     ["tag", "dice_iris_mean", "dice_iris_median", "fail_rate_dice<0.8", "hd95_median", "dice_pupil_mean",
                      "pupil_center_err_median", "ms_p50", "ms_p95", "seg_ok_rate"],
                     ["config", "Dice mean", "Dice median", "fail", "HD95 px", "pupil Dice", "pupil ctr err", "ms p50", "ms p95", "ok"]),
               "", "</details>", ""]
    if seg_x:
        md += ["### Cross-dataset generalisation", "",
               table(sorted(seg_x, key=lambda r: -r["dice_iris_mean"]),
                     ["tag", "dataset", "dice_iris_mean", "fail_rate_dice<0.8", "dice_pupil_mean", "ms_p50"]), ""]
    q = read("quality/summary.csv")
    if q:
        md += ["## 3. Capture-quality gate (synthetic degradations of held-out real images)", "",
               table(q, ["degradation", "default_recall_s1", "default_recall_s0.5", "calibrated_recall_s1",
                         "calibrated_recall_s0.5", "auc_focus_lap_iris", "auc_logistic", "auc_calibrated_rules"],
                     ["degradation", "default gate recall (sev 1)", "(sev .5)", "calibrated recall (sev 1)", "(sev .5)",
                      "AUC iris focus", "AUC logistic", "AUC calibrated rules"]), ""]
    c = read("color/summary.csv")
    if c:
        st = json.loads((R / "color/stability.json").read_text()) if (R / "color/stability.json").exists() else {}
        md += ["## 4. Iris colour (pilot hand labels, subject-grouped 5-fold CV)", "",
               table(c[:12], ["feature", "model", "margin", "macro_f1", "accuracy", "uncertain_rate", "f1_on_decided"]), "",
               f"Same-eye stability (share of an eye's images given its majority class): `{json.dumps(st.get('majority_agreement', {}))}`", ""]
    m = read("markings/injection_summary.csv")
    if m:
        best = {}
        for d in m:
            if d["norm"] != "64x512":
                continue
            if d["kind"] not in best or d["score"] > best[d["kind"]]["score"]:
                best[d["kind"]] = d
        md += ["## 5. Marking candidates (SYNTHETIC injection into real UBIRIS irises)", "",
               "> These numbers measure whether a detector finds an injected marking of known size/contrast "
               "in real iris texture. They are **not** agreement with a practitioner and must not be read as clinical accuracy.", "",
               "Best operating point per marking (64x512 normalisation, score = recall@full strength − 0.1 × FP per clean image):", "",
               table(list(best.values()), ["kind", "method", "k", "recall@s1.0", "recall@s0.5", "fp_per_clean_image",
                                           "loc_iou@s1.0", "ms_mean"]), "",
               "<details><summary>All marking configs</summary>", "",
               table(m, ["kind", "method", "k", "norm", "recall@s1.0", "recall@s0.5", "fp_per_clean_image", "loc_iou@s1.0", "ms_mean"]),
               "", "</details>", ""]
    s = read("markings/structure_summary.csv")
    if s:
        md += ["### Collarette radius & fibre orientation (procedural eyes, known truth)", "",
               table(s, ["task", "method", "norm", "radius_frac_mae", "within_0.05", "accuracy", "n"]), ""]
    e = read("e2e/summary.csv")
    if e:
        md += ["## 6. End-to-end two-eye scan (SRS budgets: quality < 2 s, analysis < 30 s)", "",
               table(e, ["pipeline", "threads", "precheck_ms_p95", "scan_ms_p50", "scan_ms_p95", "peak_rss_mb",
                         "rate_accepted", "rate_review", "rate_retake", "candidates_per_eye"]), ""]
    (R / "BENCHMARK.md").write_text("\n".join(md))
    print("wrote results/BENCHMARK.md")


if __name__ == "__main__":
    main()
